import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
const root=resolve(process.argv[2]||".");
const source=readFileSync(resolve(root,"web/urban-plan.js"),"utf8");
const module=await import("data:text/javascript;base64,"+Buffer.from(source).toString("base64"));
const report=module.auditUrbanPlan();
assert.equal(report.ok,true,JSON.stringify(report));
assert.equal(report.collisions.length,0);
assert.equal(report.setbacks.length,0);
assert.equal(report.roadDisconnections.length,0);
assert.equal(report.unreachable.length,0);
assert.ok(report.parcels>=15);
assert.ok(report.roads>=8);
const levels=[0,1,2,3,4].map(n=>module.writerHouseDimensions(n));
assert.deepEqual(module.writerHouseDimensions(module.writerHouseLevel(0)),[4.8,4.8]);
assert.deepEqual(module.writerHouseDimensions(module.writerHouseLevel(3)),[4.8,4.8]);
assert.ok(module.writerHouseLevel(5)>module.writerHouseLevel(0));
assert.ok(levels.every(([w,d],i)=>i===0||(w>=levels[i-1][0]&&d>=levels[i-1][1])));
assert.ok(module.BUILDING_PARCELS.find(p=>p.id==="writer").parking===0);
console.log("URBAN-PLAN-OK "+JSON.stringify(report));
