import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildCivitaWriterExterior,CIVITA_WRITER_HOUSE_EVIDENCE} from '../web/civita-writer-house.js';
const threeText=readFileSync(new URL('../web/vendor/three.module.js',import.meta.url),'utf8');
const THREE=await import('data:text/javascript;base64,'+Buffer.from(threeText).toString('base64'));
const scene=new THREE.Scene(),author=new THREE.Group();author.name='writer-interior-street-level';author.position.y=.2;scene.add(author);
const appearance=new THREE.Mesh(new THREE.BoxGeometry(.5,1.8,.2));appearance.name='writer-unchanged';author.add(appearance);
const exterior=new THREE.Group();exterior.name='writer-home-exterior-v2';exterior.position.y=3.2;scene.add(exterior);
const result=buildCivitaWriterExterior(THREE,exterior,{roomWidth:6,roomDepth:6,streetY:-3,parentOffsetY:3.2});
scene.updateMatrixWorld(true);
const shell=result.group,box=new THREE.Box3().setFromObject(shell);
assert.equal(shell.name,'civita-writer-house-tufa-exterior-study');
assert.equal(CIVITA_WRITER_HOUSE_EVIDENCE.storyCountReference,2);
assert.equal(shell.userData.cityArchitectureEvidence.actualLoStudioParcelMatched,undefined);
assert.equal(shell.userData.cityArchitectureEvidence.matchedToActualLoStudio,false);
assert.ok(box.min.y>=-3.08&&box.min.y<=-2.85);
assert.ok(box.max.y>4.4&&box.max.y<5.7);
assert.equal(author.children[0],appearance);
assert.equal(appearance.parent,author);
assert.equal(author.position.y,.2);
assert.equal(result.entrance.userData.writerExterior,true);
assert.equal(result.clickArea.userData.writerExterior,true);
assert.ok(shell.children.some(x=>x.name.startsWith('terracotta-sloped-roof')));
assert.ok(shell.children.some(x=>x.name.includes('peperino')));
assert.equal(shell.userData.cityArchitectureEvidence.physicalCollider,false);
console.log('CIVITA-WRITER-HOME-OK',JSON.stringify({parts:shell.children.length,bounds:[box.min.toArray(),box.max.toArray()],appearanceUnchanged:true,parcelVerified:false}));
