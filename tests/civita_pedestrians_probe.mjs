import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createCivitaPedestrians} from '../web/civita-pedestrians.js';
const source=readFileSync(new URL('../web/vendor/three.module.js',import.meta.url),'utf8');
const THREE=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const parent=new THREE.Group();
const paths=Array.from({length:12},(_,i)=>({id:'way/'+(101+i),provenance:{source_url:'https://www.openstreetmap.org/way/'+(101+i)},points:[{x:20+i*2,z:30},{x:35+i*2,z:30}]}));
const result=createCivitaPedestrians(THREE,parent,paths);
assert.equal(result.count,12);
assert.equal(parent.children[0].name,'civita-osm-footpath-visual-pedestrians');
assert.equal(parent.children[0].userData.actualPopulationVerified,false);
result.update(1,0);
const p=result.group.children[0],before=p.position.x;
result.update(1,8);
assert.notEqual(p.position.x,before);
assert.equal(p.userData.physicalCollider,false);
assert.equal(p.userData.sourceWay,'way/101');
result.update(0,12);
assert.ok(result.group.children.filter(c=>c.visible).length<result.count);
assert.ok(result.group.children.every(c=>c.userData.identity==='anonymous visual proxy'));
console.log('CIVITA-PEDESTRIANS-OK',JSON.stringify({visibleAtNight:result.group.children.filter(c=>c.visible).length,sourceLinked:result.count}));
